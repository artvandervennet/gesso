// Builds css/core.css, css/themes/*.css, css/tokens.css, components/themes.js and scss/_keys.scss
// from tokens/tokens.json and tokens/themes.json.
// Usage: node scripts/build-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadThemes, PAINT_COUNT } from './theme.mjs';
import { themeCss } from './theme-css.mjs';
import { mkdirSync } from 'node:fs';
import { oklchToHex } from './color.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'tokens/tokens.json'), 'utf8'));
const themes = loadThemes(JSON.parse(readFileSync(join(root, 'tokens/themes.json'), 'utf8')));

const isToken = (n) => n && typeof n === 'object' && '$value' in n;
const entries = (obj) => Object.entries(obj).filter(([k]) => !k.startsWith('$'));

export function cssName(path) {
  const [group, ...rest] = path;
  switch (group) {
    case 'font':
      if (rest[0] === 'family') return `--font-${rest[1]}`;
      if (rest[0] === 'size') return `--step-${rest[1]}`;
      return `--${rest.join('-')}`;
    case 'space': return `--space-${rest[0]}`;
    case 'radius': return `--radius-${rest[0]}`;
    case 'shadow': return `--shadow-${rest[0]}`;
    case 'layout': return rest[0] === 'canvas' ? '--canvas-max' : `--${rest[0]}`;
    case 'motion': return rest[0] === 'duration' ? `--dur-${rest[1]}` : `--ease-${rest[1]}`;
    default: return `--${path.join('-')}`;
  }
}
const value = (v) => (Array.isArray(v) ? `cubic-bezier(${v.join(', ')})` : String(v));
function walk(node, path, out) {
  for (const [k, child] of entries(node)) {
    const p = [...path, k];
    if (isToken(child)) out.push([cssName(p), value(child.$value), child.$description]);
    else if (child && typeof child === 'object') walk(child, p, out);
  }
  return out;
}
const decl = (list, indent = '  ') => list.map(([n, v, d]) => `${indent}${n}: ${v};${d ? ` /* ${d} */` : ''}`).join('\n');

const shared = [];
for (const [k, node] of entries(tokens)) if (k !== 'text') walk(node, [k], shared);

const paintBlocks = Array.from({ length: PAINT_COUNT }, (_, i) => `[data-paint="${i + 1}"] { --surface: var(--paint-${i + 1}); --surface-sunken: var(--paint-${i + 1}-sunken); --rule: var(--paint-${i + 1}-rule); }`).join('\n');

// Text styles become classes.
const ref = (v) => String(v).replace(/^\{font\.family\.(\w+)\}$/, 'var(--font-$1)').replace(/^\{font\.size\.(-?\d+)\}$/, 'var(--step-$1)');
const textClasses = entries(tokens.text).map(([name, tok]) => {
  const v = tok.$value;
  return `.text-${name} { /* ${tok.$description} */\n  font-family: ${ref(v.fontFamily)};\n  font-size: ${ref(v.fontSize)};\n  font-weight: ${v.fontWeight};\n  line-height: ${v.lineHeight};\n  letter-spacing: ${v.letterSpacing};\n}`;
}).join('\n');

const header = (what) => `/* Gesso ${what} — generated by scripts/build-tokens.mjs. Do not edit by hand. */\n\n`;
const core = `:root {
${decl(shared)}
}

/* Paints: put data-paint="deep" or "1"…"${PAINT_COUNT}" on a section to paint it.
   Every theme has its own colours for the same numbers. */
[data-paint] { background-color: var(--surface); color: var(--ink); }
${paintBlocks}

/* Text styles */
${textClasses}
`;

// 1. core.css: everything except colours. Every project loads it.
writeFileSync(join(root, 'css/core.css'), header('core: shared tokens, paints and text styles, no colours') + core);

// 2. themes/<id>.css: one theme each, applied to the whole page. A project loads exactly one.
mkdirSync(join(root, 'css/themes'), { recursive: true });
for (const t of themes) writeFileSync(join(root, `css/themes/${t.id}.css`), header(`theme "${t.id}"`) + themeCss(t, { standalone: true }));

// 3. tokens.css: core plus every theme, switched with data-theme. For pages that compare themes, like the docs.
writeFileSync(join(root, 'css/tokens.css'), header('tokens: core plus all themes, switched with <html data-theme>') + core + '\n' + themes.map((t, i) => themeCss(t, { standalone: false, isDefault: i === 0 })).join('\n'));

// A small module the components and docs use to list themes (names, codes and a few hex values for previews).
const meta = themes.map((t) => ({
  id: t.id, label: t.label, description: t.description,
  pigments: Object.fromEntries(Object.entries(t.pigment).map(([k, p]) => [k, { name: p.name, code: p.code, hex: oklchToHex(p.body) }])),
  deep: oklchToHex(t.paints.deep.surface),
  paints: Array.from({ length: PAINT_COUNT }, (_, i) => oklchToHex(t.paints[i + 1].surface)),
}));
writeFileSync(join(root, 'components/themes.js'), `// Generated by scripts/build-tokens.mjs from tokens/themes.json. Do not edit by hand.\nexport const THEMES = ${JSON.stringify(meta, null, 2)};\nexport const PAINT_COUNT = ${PAINT_COUNT};\n`);

// 4. scss/_keys.scss: every custom property the system defines, as a Sass list. The functions in
// scss/_functions.scss check against it, so a token that doesn't exist fails the build.
const allCss = core + themes.map((t) => themeCss(t, { standalone: true })).join('\n');
const names = [...new Set([...allCss.matchAll(/(?<![\w-])--([a-z][\w-]*)\s*:/g)].map((m) => m[1]))].sort();
mkdirSync(join(root, 'scss'), { recursive: true });
writeFileSync(join(root, 'scss/_keys.scss'), `// Generated by scripts/build-tokens.mjs. Do not edit by hand.\n$properties: (\n${names.map((n) => `  '${n}',`).join('\n')}\n);\n`);

console.log(`tokens.css: ${shared.length} shared tokens, ${themes.length} themes (${themes.map((t) => t.id).join(', ')}), ${PAINT_COUNT} paints + deep each`);
