#!/usr/bin/env node
// gesso-theme — build a project's own Gesso theme from a recipe.
//
//   npx gesso-theme theme.json                     → writes gesso-theme.css next to it
//   npx gesso-theme theme.json --out src/styles/theme.css --hex src/styles/theme.hex.json
//
// theme.json is one recipe:
//   {
//     "id": "harbour",
//     "label": "Harbour",
//     "brand":      { "name": "Prussian blue",  "code": "PB27", "oklch": [40, 0.09, 238] },
//     "partner":    { "name": "Naples yellow",  "code": "PY35", "oklch": [87, 0.09, 92] },
//     "complement": { "name": "Cadmium orange", "code": "PO20", "oklch": [60, 0.15, 48] }
//   }
// The generator mixes the shades and the eight section paints, fixes anything that would fail
// contrast, checks every pairing in every paint, and writes one CSS file that themes the whole page.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { buildTheme, PAIRS, rolesIn, SCHEMES } from '../scripts/theme.mjs';
import { themeCss } from '../scripts/theme-css.mjs';
import { contrast, oklchToHex } from '../scripts/color.mjs';

const args = process.argv.slice(2);
const flag = (name) => { const i = args.indexOf(name); return i === -1 ? null : args.splice(i, 2)[1]; };
const help = args.includes('--help') || args.includes('-h');
const outArg = flag('--out');
const hexArg = flag('--hex');
const input = args.find((a) => !a.startsWith('-'));

if (help || !input) {
  console.log(`Usage: gesso-theme <recipe.json> [--out theme.css] [--hex theme.hex.json]

  <recipe.json>  a theme recipe: id, label, and brand, partner and complement pigments in OKLCH
  --out          where to write the CSS (default: gesso-theme.css next to the recipe)
  --hex          also write every colour as hex, per paint, for design tools`);
  process.exit(input ? 0 : 1);
}

const recipePath = resolve(input);
let recipe;
try { recipe = JSON.parse(readFileSync(recipePath, 'utf8')); }
catch (e) { console.error(`Couldn't read ${input}: ${e.message}`); process.exit(1); }

for (const k of ['brand', 'partner', 'complement']) {
  const p = recipe[k];
  if (!p || !Array.isArray(p.oklch) || p.oklch.length !== 3) {
    console.error(`${input} needs "${k}": { "name": "...", "oklch": [lightness %, chroma, hue] }, for example [41, 0.105, 168].`);
    process.exit(1);
  }
  p.name ??= k; p.code ??= '';
}
const id = String(recipe.id || 'custom').replace(/[^a-z0-9-]/gi, '-').toLowerCase();
recipe.label ??= id;

const theme = buildTheme(id, recipe);

// Check every pairing in every paint.
const fails = [];
for (const paint of Object.keys(theme.paints)) {
  for (const scheme of SCHEMES) {
    const roles = rolesIn(theme, paint, scheme);
    for (const [fg, bg, min, why] of PAIRS) {
      const r = contrast(roles[fg], roles[bg]);
      if (r < min) fails.push(`  ${r.toFixed(2)}:1 (needs ${min})  ${fg} on ${bg}, paint ${paint}, ${scheme}: ${why}`);
    }
  }
}
if (fails.length) {
  console.error(`The "${theme.label}" theme fails contrast in ${fails.length} places:\n${fails.join('\n')}\nTry a brand colour with a lightness between 30 and 50, and a partner above 75.`);
  process.exit(1);
}

const out = resolve(outArg || join(dirname(recipePath), 'gesso-theme.css'));
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `/* Gesso theme "${id}", generated by gesso-theme from ${input}. Do not edit by hand. */\n\n` + themeCss(theme, { standalone: true }));
console.log(`Wrote ${out}: the "${theme.label}" theme, light and dark, every pairing passes AA.`);

if (hexArg) {
  const hex = Object.fromEntries(Object.keys(theme.paints).map((paint) => [paint, Object.fromEntries(Object.entries(rolesIn(theme, paint)).map(([k, v]) => [k, oklchToHex(v)]))]));
  const pigments = Object.fromEntries(Object.entries(theme.pigment).map(([k, p]) => [k, { name: p.name, code: p.code, body: oklchToHex(p.body), light: oklchToHex(p.light), wash: oklchToHex(p.wash) }]));
  const hexOut = resolve(hexArg);
  mkdirSync(dirname(hexOut), { recursive: true });
  writeFileSync(hexOut, JSON.stringify({ id, label: theme.label, pigments, paints: hex }, null, 2) + '\n');
  console.log(`Wrote ${hexOut}: every colour as hex, per paint, for design tools.`);
}
